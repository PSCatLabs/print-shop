import {spawn} from 'node:child_process';
import {mkdtemp,mkdir,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const chrome=process.env.CHROME_BIN||(process.platform==='darwin'?'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome':'chromium');
const profile=await mkdtemp(path.join(os.tmpdir(),'printshop-browser-'));
const url=pathToFileURL(path.resolve('dist/printshop-offline.html')).href+'?browser-test';
await mkdir('artifacts',{recursive:true});
const args=['--headless','--disable-gpu','--no-first-run','--no-default-browser-check',`--user-data-dir=${profile}`,'--disable-background-networking','--disable-extensions','--timeout=60000','--window-size=1440,1400','--screenshot='+path.resolve('artifacts/browser-desktop.png'),'--dump-dom',url];
const child=spawn(chrome,args,{stdio:['ignore','pipe','pipe']});
let stdout='',stderr='';
child.stdout.on('data',chunk=>stdout+=chunk);child.stderr.on('data',chunk=>stderr+=chunk);
const timer=setTimeout(()=>child.kill('SIGKILL'),75000);
let signal;
const code=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',(code,closedSignal)=>{signal=closedSignal;resolve(code);});}).finally(()=>clearTimeout(timer));
await writeFile('artifacts/browser.log',stderr);
const match=/<pre id="browser-test-report">([\s\S]*?)<\/pre>/.exec(stdout);
if(code!==0||!match)throw Error(`Browser checks did not complete (exit ${code}, signal ${signal||'none'}). See artifacts/browser.log.`);
const decoded=match[1].replace(/&quot;/g,'"').replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>');
const report=JSON.parse(decoded);await writeFile('artifacts/browser-report.json',JSON.stringify(report,null,2)+'\n');
console.log(decoded);
if(report.state!=='passed')process.exitCode=1;
